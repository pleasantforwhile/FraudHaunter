@router.callback_query(F.data.startswith("gen_audience_"))
async def generator_step3(callback: CallbackQuery):
    audience_key = callback.data.replace("gen_audience_", "")

    if callback.from_user.id not in generator_state:
        await callback.answer("Ошибка: сессия не найдена")
        return

    state = generator_state[callback.from_user.id]
    state["audience"] = audience_key

    responses = generate_responses(state)

    result_text = (
        f"🛡️ *Ваши защитные фразы готовы!*\n\n"
        f"*Параметры:*\n"
        f"• Стиль: {STYLE_OPTIONS[state['style']]}\n"
        f"• Цель: {GOAL_OPTIONS[state['goal']]}\n"
        f"• Роль мошенника: {AUDIENCE_OPTIONS[audience_key]}\n\n"
        f"*Скопируйте подходящий вариант:*\n\n"
    )

    for i, response in enumerate(responses, 1):
        result_text += f"*Вариант {i}:*\n"
        result_text += f"`{response['text']}`\n\n"
        result_text += f"*Почему это работает:* {response['explanation']}\n\n"
        result_text += "---\n\n"

    result_text += "*Совет:* Не импровизируйте под давлением. Используйте готовую фразу и сразу кладите трубку."

    keyboard = [
        [InlineKeyboardButton(text="🔄 Создать еще", callback_data="generator_start")],
        [InlineKeyboardButton(text="🏠 В меню", callback_data="main_menu")]
    ]

    await callback.message.edit_text(
        result_text,
        reply_markup=InlineKeyboardMarkup(inline_keyboard=keyboard),
        parse_mode="Markdown"
    )
    await callback.answer()


def generate_responses(state):
    style = state.get("style")
    goal = state.get("goal")
    audience = state.get("audience")

    key = (style, goal, audience)
    if key in RESPONSE_TEMPLATES:
        return RESPONSE_TEMPLATES[key]

    key_with_audience = (style, goal, audience)
    if key_with_audience in RESPONSE_TEMPLATES:
        return RESPONSE_TEMPLATES[key_with_audience]

    key_any_audience = (style, goal, "any")
    if key_any_audience in RESPONSE_TEMPLATES:
        return RESPONSE_TEMPLATES[key_any_audience]

    return RESPONSE_TEMPLATES[("provocative", "verify", "any")]

