@router.callback_query(F.data.startswith("trainer_answer_"))
async def trainer_answer(callback: CallbackQuery):
    _, __, scenario_id_str, step_str, answer_idx_str = callback.data.split("_")
    scenario_id = int(scenario_id_str)
    step = int(step_str)
    answer_idx = int(answer_idx_str)

    scenario = next((s for s in TRAINING_SCENARIOS if s.id == scenario_id), None)
    if not scenario or step >= len(scenario.steps):
        await callback.answer("Ошибка")
        return

    question, answers, correct_idx = scenario.steps[step]
    
    session = user_sessions.get(callback.from_user.id, (scenario_id, 0, 0))
    new_score = session[2] + (1 if answer_idx == correct_idx else 0)
    user_sessions[callback.from_user.id] = (scenario_id, step + 1, new_score)

    feedback = "✅ *Правильно!*" if answer_idx == correct_idx else "❌ *Неправильно!*"
    explanation = f"\n\n*Объяснение:* Вы выбрали '{answers[answer_idx]}'.\n"

    if answer_idx == correct_idx:
        explanation += "Это эффективный ответ! Вы не поддались на манипуляцию."
    else:
        explanation += f"Правильный ответ был: '{answers[correct_idx]}'.\nМошенник использовал: *{scenario.method}*"

    if step + 1 < len(scenario.steps):
        builder = InlineKeyboardBuilder()
        builder.row(InlineKeyboardButton(
            text="➡️ Следующий шаг",
            callback_data=f"trainer_step_{scenario_id}_{step + 1}"
        ))
        builder.row(InlineKeyboardButton(
            text="🏁 Завершить досрочно",
            callback_data=f"trainer_finish_{scenario_id}"
        ))

        await callback.message.edit_text(
            f"{feedback}{explanation}",
            reply_markup=builder.as_markup(),
            parse_mode="Markdown"
        )
    else:
        await trainer_finish(callback, scenario_id, new_score, len(scenario.steps))

@router.callback_query(F.data.startswith("trainer_finish_"))
async def trainer_finish_handler(callback: CallbackQuery):
    scenario_id = int(callback.data.split("_")[-1])

    session = user_sessions.get(callback.from_user.id)
    if not session:
        await callback.answer("Сессия не найдена")
        return

    current_scenario_id, current_step, current_score = session
    scenario = next((s for s in TRAINING_SCENARIOS if s.id == scenario_id), None)

    if not scenario:
        await callback.answer("Сценарий не найден")
        return

    if current_scenario_id != scenario_id:
        await callback.answer("Ошибка: несовпадение сценариев")
        return

    await trainer_finish(callback, scenario_id, current_score, len(scenario.steps))


async def trainer_finish(callback: CallbackQuery, scenario_id: int, score: int = None, total: int = None):
    session = user_sessions.get(callback.from_user.id)
    if session:
        actual_scenario_id, _, actual_score = session
        if score is None:
            score = actual_score
        if scenario_id != actual_scenario_id:
            scenario_id = actual_scenario_id
    else:
        score = score or 0

    scenario = next((s for s in TRAINING_SCENARIOS if s.id == scenario_id), None)

    if not scenario:
        await callback.answer("Сценарий не найден")
        return

    if total is None:
        total = len(scenario.steps)

    percentage = (score / total * 100) if total > 0 else 0

    if percentage >= 90:
        grade = "🎖️ Отлично! Вы эксперт по безопасности!"
    elif percentage >= 70:
        grade = "👍 Вы хорошо распознаете манипуляции!"
    elif percentage >= 50:
        grade = "⚠️ Средне. Есть над чем поработать."
    else:
        grade = "📚 Нужно учиться. Рекомендуем пройти сценарий еще раз."
    result_text = (
        f"🏁 *Тренировка завершена!*\n\n"
        f"*Сценарий:* {scenario.name}\n"
        f"*Метод манипуляции:* {scenario.method}\n"
        f"*Результат:* {score}/{total} правильных ответов ({percentage:.0f}%)\n\n"
        f"*Оценка:* {grade}\n\n"
    )
    if percentage < 70:
        result_text += f"*Рекомендация:* Пройдите этот сценарий еще раз, чтобы лучше распознавать метод *{scenario.method}*.\n\n"
    result_text += "«Знание — лучшая защита. Сохраняйте бдительность!»"
    keyboard = [
        [InlineKeyboardButton(text="🔄 Пройти заново", callback_data=f"trainer_start_{scenario_id}")],
        [InlineKeyboardButton(text="📚 Выбрать другой сценарий", callback_data="menu_trainer")],
        [InlineKeyboardButton(text="🏠 В главное меню", callback_data="main_menu")]
    ]
    await callback.message.edit_text(
        result_text,
        reply_markup=InlineKeyboardMarkup(inline_keyboard=keyboard),
        parse_mode="Markdown"
    )
    user_sessions.pop(callback.from_user.id, None)
    
